import { expect, test } from "@playwright/test";
import { mockStore } from "../../services/mock-data";

test("analysis motion follows reported progress, handles unknown totals and respects reduced motion", async ({ page }) => {
  const id = "RAV-18-0042";
  let job = { job_id: "J-UI", status: "queued", pass: null as number | null, progress: { done: 0, total: null as number | null }, error: null as { message: string } | null };
  await page.addInitScript(id => sessionStorage.setItem(`analysis-job:${id}`, "J-UI"), id);
  await page.route("**/api/v1/**", async route => {
    const path = new URL(route.request().url()).pathname;
    if (path.endsWith("/auth/me")) return route.fulfill({ json: { csrf_token: "fixture", user: { id: "engineer", email: "fixture@example.com", display_name: "Engineer", roles: ["engineer"], is_active: true, must_change_password: false } } });
    if (path.endsWith("/latest-job")) return route.fulfill({ json: { job_id: "J-UI" } });
    if (path.endsWith("/jobs/J-UI")) return route.fulfill({ json: { ...job, updated_at: new Date().toISOString(), result_uri: null } });
    if (path.endsWith("/report")) return route.fulfill({ json: mockStore.getDraft(id) });
    if (path.endsWith("/evidence")) return route.fulfill({ json: { items: [] } });
    if (path === `/api/v1/incidents/${id}`) return route.fulfill({ json: { ...mockStore.getIncident(id), processing_status: "PROCESSING" } });
    return route.fulfill({ status: 404, json: { error: { code: "NOT_FOUND", message: "Fixture unavailable" } } });
  });
  await page.goto(`/incidents/${id}/processing`);
  const progress = page.getByRole("progressbar", { name: "Analysis progress", exact: true });
  const panel = page.locator(".analysis-progress");
  const activity = page.locator(".analysis-progress-activity");
  const fill = page.locator(".analysis-progress-fill");
  await expect(panel).toHaveAttribute("data-state", "queued");
  await expect(progress).not.toHaveAttribute("aria-valuenow");
  expect(await activity.evaluate(el => getComputedStyle(el).animationName)).toBe("analysis-progress-sweep");
  await page.emulateMedia({ reducedMotion: "reduce" });
  expect(await activity.evaluate(el => getComputedStyle(el).animationName)).toBe("none");
  expect(await fill.evaluate(el => getComputedStyle(el).transitionDuration)).toBe("0s");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  job = { ...job, status: "running", pass: 1, progress: { done: 2, total: 10 } };
  await expect(progress).toHaveAttribute("aria-valuenow", "10");
  job = { ...job, progress: { done: 8, total: 10 } };
  await expect(progress).toHaveAttribute("aria-valuenow", "40");
  const displayed = () => panel.locator(".analysis-progress-value").evaluate(el => parseInt(el.textContent || "0", 10));
  expect(await displayed()).toBeLessThan(40);
  const scale = () => fill.evaluate(el => Number(getComputedStyle(el).transform.match(/^matrix\(([^,]+)/)?.[1]));
  expect(await scale()).toBeLessThan(.4);
  await expect.poll(scale).toBeCloseTo(.4, 2);
  await expect.poll(displayed).toBe(40);
  await page.screenshot({ path: test.info().outputPath("analysis-progress-running.png"), fullPage: true });
  job = { ...job, pass: 2, progress: { done: 0, total: null } };
  await expect(progress).not.toHaveAttribute("aria-valuenow");
  await expect(panel.locator(".analysis-progress-value")).toHaveText("Working");
  job = { ...job, status: "failed", progress: { done: 4, total: 10 }, error: { message: "Fixture stopped" } };
  await expect(panel).toHaveAttribute("data-active", "false");
  expect(await activity.evaluate(el => getComputedStyle(el).animationName)).toBe("none");
  job = { ...job, status: "succeeded", progress: { done: 10, total: 10 }, error: null };
  await page.reload();
  await expect(progress).toHaveAttribute("aria-valuenow", "100");
  await expect(page.getByRole("link", { name: "Open review" })).toBeVisible();
  await expect(panel).toHaveAttribute("data-active", "false");
});
