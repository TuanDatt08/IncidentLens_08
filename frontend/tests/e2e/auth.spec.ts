import { expect, test, type Page } from "@playwright/test";

const tempPassword = "aB3!xy";
const password = "cD4!yz";

async function signIn(page: Page, email: string, secret = password) {
  await page.goto("/login");
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Password", { exact: true }).fill(secret);
  const response = page.waitForResponse(item => item.url().endsWith("/api/v1/auth/login") && item.request().method() === "POST");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  if ((await response).status() === 200) await expect(page).toHaveURL(/\/(incidents|change-password)/);
}

test("anonymous guard, temporary password, workflow, authenticated Range and logout", async ({ page, browser }) => {
  await page.goto("/incidents");
  await expect(page).toHaveURL(/\/login/);
  await expect(page.getByLabel("Email", { exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/auth-login-desktop.png", fullPage: true });
  await signIn(page, "engineer@example.com", tempPassword);
  await expect(page).toHaveURL(/\/change-password/);
  await page.screenshot({ path: "test-results/auth-change-password.png", fullPage: true });
  await page.getByLabel("Current password", { exact: true }).fill(tempPassword);
  await page.getByLabel("New password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Change password", exact: true }).click();
  await expect(page).toHaveURL(/\/login/);
  await signIn(page, "engineer@example.com");
  await expect(page).toHaveURL(/\/incidents/);
  await page.goto("/incidents/new");
  await page.locator('input[type="file"]').nth(0).setInputFiles("tests/e2e/fixtures/video.mp4");
  await page.locator('input[type="file"]').nth(1).setInputFiles({ name: "log.csv", mimeType: "text/csv", buffer: Buffer.from("sec_from_incident,sim_time_s\n-1,9\n0,10\n1,11\n") });
  await page.getByRole("button", { name: "Create Incident" }).click();
  await page.getByRole("button", { name: "Start analysis", exact: true }).click();
  await expect(page.getByRole("link", { name: /review/i }).last()).toBeVisible({ timeout: 45000 });
  const incident = page.url().match(/incidents\/(INC-[^/]+)/)![1];
  const videoUrl = `/api/v1/incidents/${incident}/video`;
  const range = await page.request.get(videoUrl, { headers: { Range: "bytes=0-6" } });
  expect(range.status()).toBe(206);
  expect(range.headers()["content-range"]).toMatch(/^bytes 0-6\/\d+$/);
  expect((await page.request.get(videoUrl, { headers: { Range: "bytes=99999999-" } })).status()).toBe(416);
  await page.goto(`/incidents/${incident}`);
  await page.getByRole("button", { name: "Report", exact: true }).click();
  await page.getByLabel("Summary text").fill("Engineer verified browser draft");
  await page.getByRole("button", { name: "History", exact: true }).click();
  await expect(page.getByLabel("Summary text")).toBeHidden();
  await page.getByRole("button", { name: "Report", exact: true }).click();
  await expect(page.getByLabel("Summary text")).toHaveValue("Engineer verified browser draft");
  await page.getByRole("button", { name: "Save Changes" }).click();
  await expect(page.getByText("Changes saved.")).toBeVisible();
  await page.getByRole("button", { name: "Submit for Review" }).click();
  await page.getByRole("button", { name: "Submit", exact: true }).click();
  await expect(page.getByText("In review", { exact: true }).first()).toBeVisible();
  const reviewerContext = await browser.newContext();
  const reviewer = await reviewerContext.newPage();
  await signIn(reviewer, "reviewer@example.com");
  await reviewer.goto(`/incidents/${incident}`);
  await reviewer.getByRole("button", { name: "Report", exact: true }).click();
  await expect(reviewer.getByLabel("Summary text")).toBeDisabled();
  await reviewer.getByRole("button", { name: "Approve", exact: true }).click();
  await reviewer.getByRole("dialog").getByRole("button", { name: "Approve", exact: true }).click();
  await expect(reviewer.getByText("Report approved", { exact: true })).toBeVisible();
  await reviewer.getByRole("button", { name: "Account menu" }).click();
  await reviewer.getByRole("button", { name: "Sign out" }).click();
  await expect(reviewer).toHaveURL(/\/login/);
  expect((await reviewer.request.get(videoUrl)).status()).toBe(401);
  await reviewerContext.close();
});

