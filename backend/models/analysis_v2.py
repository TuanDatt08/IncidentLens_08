"""Strict business and AI-output models for the versioned V2 boundary.

Use AIIncidentAnalysisV2 for generated drafts and IncidentAnalysisV2 for human
review snapshots. Call model_json_schema() for the corresponding JSON Schema.
Evidence registry resolution belongs to the processing/review validator.
"""

from __future__ import annotations

import math
from typing import Annotated, Literal, Self

from pydantic import BaseModel, ConfigDict, Field, ValidationInfo, model_validator

ClaimStatus = Literal["OBSERVED", "SUPPORTED_INFERENCE", "HYPOTHESIS", "UNKNOWN"]
EventType = Literal["DISENGAGEMENT", "HARD_BRAKING", "COLLISION", "CONTROL_ANOMALY", "OTHER", "UNKNOWN"]
EvidenceSource = Literal["VIDEO", "TELEMETRY", "FUSED"]
FactorCategory = Literal["EXTERNAL_CONDITION", "VEHICLE_OR_SYSTEM", "HUMAN_INTERACTION", "UNKNOWN"]
ReviewStatus = Literal["DRAFT", "IN_REVIEW", "APPROVED", "REJECTED"]
NonblankText = Annotated[str, Field(min_length=1, pattern=r"\S")]
VideoSecond = Annotated[float, Field(ge=0)]


class ClosedModel(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True, allow_inf_nan=False)


class AnalysisWindowV2(ClosedModel):
    start_s: VideoSecond
    critical_s: VideoSecond
    end_s: VideoSecond

    @model_validator(mode="after")
    def ordered(self) -> Self:
        if not self.start_s <= self.critical_s <= self.end_s or self.start_s >= self.end_s:
            raise ValueError("window must have positive length and contain critical_s")
        return self


class TimelineObservationV2(ClosedModel):
    time_s: VideoSecond
    observation: NonblankText
    evidence_ids: list[NonblankText]
    source: EvidenceSource
    certainty: ClaimStatus

    @model_validator(mode="after")
    def supported_evidence(self) -> Self:
        if self.certainty in {"OBSERVED", "SUPPORTED_INFERENCE"} and not self.evidence_ids:
            raise ValueError("supported observation requires evidence_ids")
        return self


class AnalysisFactorV2(ClosedModel):
    category: FactorCategory
    label: NonblankText
    claim_status: ClaimStatus
    evidence_ids: list[NonblankText]

    @model_validator(mode="after")
    def supported_evidence(self) -> Self:
        if self.claim_status in {"OBSERVED", "SUPPORTED_INFERENCE"} and not self.evidence_ids:
            raise ValueError("supported factor requires evidence_ids")
        return self


class IncidentAnalysisV2(ClosedModel):
    schema_version: Literal["2.0"]
    incident_detected: bool
    event_type: EventType
    time_basis: Literal["video_seconds"]
    window: AnalysisWindowV2 | None
    summary: NonblankText
    timeline: list[TimelineObservationV2]
    factors: list[AnalysisFactorV2]
    unknowns: list[NonblankText]
    review_status: ReviewStatus

    @model_validator(mode="after")
    def consistent_analysis(self, info: ValidationInfo) -> Self:
        if not self.incident_detected:
            if self.window is not None or self.timeline or self.factors or self.event_type != "UNKNOWN":
                raise ValueError("no detection requires null window, UNKNOWN event and empty claims")
            if self.review_status == "APPROVED":
                raise ValueError("no detection cannot be approved as an incident report")
        elif self.window is None:
            raise ValueError("detected incident requires a window")

        if self.window is not None:
            if any(not self.window.start_s <= item.time_s <= self.window.end_s for item in self.timeline):
                raise ValueError("timeline timestamp must be inside the incident window")

        # Duration is trusted media metadata, never a field generated by the AI.
        if info.context is not None and "video_duration_s" in info.context:
            duration = info.context["video_duration_s"]
            if (
                isinstance(duration, bool)
                or not isinstance(duration, (int, float))
                or not math.isfinite(duration)
                or duration <= 0
            ):
                raise ValueError("video_duration_s must be a finite positive number")
            if self.window is not None and self.window.end_s > duration:
                raise ValueError("incident window exceeds the source video duration")
        return self


class AIIncidentAnalysisV2(IncidentAnalysisV2):
    """Provider output cannot submit, reject or approve a report."""

    review_status: Literal["DRAFT"]
